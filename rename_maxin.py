def fix_body(body):
    for a, b in GARBLE:
        body = body.replace(a, b)
    return body

files = sorted(f for f in os.listdir(base) if f.endswith('.md'))
renames, skipped, used_targets = [], [], set()

for fname in files:
    if fname in ('_meta.md',):
        continue
    stem, ext = os.path.splitext(fname)
    m = re.match(r'^(\d{2})-(.+)$', stem)
    page_m = re.search(r'-(\d{2,3})$', stem)

    page = int(page_m.group(1)) if page_m else None
    new_stem = stem
    cur_prefix = int(m.group(1)) if m else None
    body_rest = m.group(2) if m else stem
    body_fixed = fix_body(body_rest)
    kw = kw_chapter(body_fixed)

    if m and cur_prefix and 1 <= cur_prefix <= 25 and kw == cur_prefix:
        # 规则1：现前缀有效且与关键词一致 → 保留前缀，仅修乱码
        new_stem = f'{cur_prefix:02d}-{body_fixed}'
    elif page is not None:
        # 规则2：页码后缀 → 按页码归章
        ch_num, ch_name = chapter_by_page(page)
        if ch_num:
            ch_short = ch_name.split('（')[0]
            body = re.sub(r'^\d+-', '', stem)
            body = fix_body(body)
            # 去横线后比较，避免"阐释接受理论"误判为不含"阐释-接受理论"
            if ch_short.replace('-', '') not in body.replace('-', ''):
                body = f'{ch_name}-{body}'
            new_stem = f'{ch_num:02d}-{body}'
    elif kw is not None:
        # 规则3：关键词归章
        body = re.sub(r'^\d+-', '', body_fixed)
        new_stem = f'{kw:02d}-{body}'
    elif body_fixed != body_rest:
        # 规则4：仅修乱码
        new_stem = (f'{cur_prefix:02d}-{body_fixed}' if m else body_fixed)

    if new_stem == stem:
        continue
    target = new_stem + ext
    n = 0
    suffixes = ['-b', '-c', '-d', '-e']
    while (target in used_targets or os.path.exists(os.path.join(base, target))) and n < len(suffixes):
        target = f'{new_stem}{suffixes[n]}{ext}'
        n += 1
    used_targets.add(target)
    renames.append((fname, target))

print(f'计划重命名: {len(renames)} / {len(files)} 个文件')
for old, new in renames:
    print(f'  {old}  ->  {new}')

# 执行
do_apply = os.environ.get('APPLY') == '1'
if do_apply:
    for old, new in renames:
        os.rename(os.path.join(base, old), os.path.join(base, new))
    print(f'\n✅ 已重命名 {len(renames)} 个文件')
else:
    print('\n[DRY RUN] 设置 APPLY=1 执行')
